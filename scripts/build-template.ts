import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { PrismaClient } from "@prisma/client";
import { seedDatabase } from "@/server/seed";

async function main() {
const root = process.cwd();
const file = path.join(root, "prisma", "template.db");
const out = path.join(root, "src", "generated", "demo-template.ts");

rmSync(file, { force: true });
rmSync(`${file}-journal`, { force: true });
mkdirSync(path.dirname(file), { recursive: true });

const previous = process.env.DATABASE_URL;
process.env.DATABASE_URL = `file:${file}`;
const schema = path.join(root, "prisma", "schema.prisma");
const cli = path.join(root, "node_modules", "prisma", "build", "index.js");
execFileSync(process.execPath, [cli, "db", "push", "--skip-generate", "--schema", schema], {
  cwd: root,
  env: process.env,
  stdio: "inherit",
});

const prisma = new PrismaClient({ datasources: { db: { url: `file:${file}` } } });
await seedDatabase(prisma);
await prisma.$queryRawUnsafe("PRAGMA wal_checkpoint(TRUNCATE)");
await prisma.$disconnect();
if (previous === undefined) delete process.env.DATABASE_URL;
else process.env.DATABASE_URL = previous;

const bytes = readFileSync(file);
writeFileSync(out, `/** Generated by scripts/build-template.ts. Not edited by hand. */\nexport const demoTemplate = ${JSON.stringify(bytes.toString("base64"))};\n`);
rmSync(file, { force: true });
rmSync(`${file}-journal`, { force: true });
rmSync(`${file}-wal`, { force: true });
rmSync(`${file}-shm`, { force: true });
console.log(`demo template embedded (${bytes.length} bytes)`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
